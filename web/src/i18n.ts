export function humanDuration(seconds: number | null | undefined, t: (k: Key) => string): string {
  if (seconds == null || isNaN(seconds)) return "—";
  const s = Math.max(0, Math.round(seconds));
  if (s < 60) return `${s} ${t("s")}`;
  if (s < 3600) return `${Math.round(s / 60)} ${t("min")}`;
  if (s < 86400) {
    const h = Math.floor(s / 3600), m = Math.round((s % 3600) / 60);
    return m ? `${h} ${t("h")} ${m} ${t("min")}` : `${h} ${t("h")}`;
  }
  const d = Math.floor(s / 86400), h = Math.round((s % 86400) / 3600);
  return h ? `${d} ${t("d")} ${h} ${t("h")}` : `${d} ${t("d")}`;
}

export function fmtUtc(v?: string | null): string {
  if (!v) return "—";
  const d = new Date(v);
  if (isNaN(d.getTime())) return String(v);
  return d.toISOString().replace("T", " ").slice(0, 19) + "Z";
}
